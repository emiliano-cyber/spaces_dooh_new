//  Lote piloto de la version en ingles (2026-11-02). Un archivo POR AREA, y no
//  todo dentro de `diccionario.ts`, por una razon practica: cada lote lo hace
//  un agente en su propia rama, y si todos escribieran en el mismo objeto cada
//  integracion seria un conflicto en el mismo bloque de lineas. Aqui cada area
//  tiene su archivo y `diccionario.ts` solo los junta.
//
//  Las reglas son las de `diccionario.ts`, sin excepcion:
//
//    · CLAVES en espanol, `propuestas.<elemento>[.matiz]`, minusculas y sin
//      acentos. La clave NO es la frase.
//    · El ESPANOL es una copia LITERAL de lo que habia escrito en el
//      componente: mismas tildes, mismas comillas «», mismos espacios en los
//      bordes. Una frase que empieza con espacio (« · vía {agencia}») lo lleva
//      porque en la pantalla iba pegada a otro nodo.
//    · `EN_PROPUESTAS` es `Record<ClavePropuestas, string>`: una clave inglesa
//      que falte NO compila.
//    · Ni una cifra de dinero, ni un simbolo de moneda (GUARDIA 2 de
//      `dinero.test.ts`). Los importes entran por hueco, ya formateados.
//    · Las frases con un trozo en negrita o con un elemento dentro van ENTERAS,
//      con huecos `{nombre}`, y se rellenan con `interpolarNodos()`
//      (`lib/i18n/nodos.ts`). Partirlas en pedazos congelaria el orden de la
//      frase espanola en el ingles.
//
//  GLOSARIO del lote (obligatorio; ampliado en
//  `vault/03-Frontend/idiomas-es-en.md`): propuesta → proposal · sitio → site ·
//  pantalla → screen · arrendador → landlord · cliente → client · campana →
//  campaign · tarifa → rate · vigencia → validity / valid until · vendedor →
//  sales rep · cupon / codigo promocional / codigo de negociacion →
//  negotiation code (decision del dueno, 2026-11-02: como el menu,
//  «Negotiation codes») · folio → Internal ref. · borrador → draft · enviar →
//  send · spots por hora del loop → loops/h. DOOH, spot, Roadblock y loop no
//  se traducen.
// ============================================================================

