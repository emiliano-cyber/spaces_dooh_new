// ============================================================================
//  lib/i18n/textos/arrendadores.ts — LOS TEXTOS DE ARRENDADORES Y CONTRATOS.
// ----------------------------------------------------------------------------
//  Lote «inventario y arrendadores» de la version en ingles (2026-11-02). Las
//  reglas son las de `textos/inventario.ts`.
//
//  ─── LO QUE NO ESTA AQUI, A PROPOSITO ──────────────────────────────────────
//  El CONTRATO no se traduce: su texto (`lib/contrato-documento.ts`), la
//  cantidad con letra y todo lo que entra en el hash de las firmas siguen en
//  espanol, y tambien lo que se IMPRIME con el documento (los encabezados, los
//  sellos de firma, la constancia de firma electronica y el aviso de borrador).
//  Un contrato en espanol con la constancia en ingles seria un papel en dos
//  idiomas, y la constancia es la prueba de lo que se firmo. Aqui solo esta lo
//  que RODEA al documento en pantalla: la barra, el panel de firmas, la firma
//  publica y los cuadros de la ficha.
//
//  Las etiquetas con su verdad en otro modulo —`textoVencimiento`
//  (`lib/renta-periodicidad.ts`), `faltaEnContratos` y `LICENCIA_LABEL`
//  (`lib/data/derive.ts`)— se traducen con `components/demo/arrendadores/
//  etiquetas.ts`, y `textos/arrendadores.test.ts` exige que su espanol sea el
//  mismo. Los estatus del contrato y del pago reutilizan las claves del lote de
//  Comercial (`comercial.contrato-estatus.*`, `comercial.pago-estatus.*`).
