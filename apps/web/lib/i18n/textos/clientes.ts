//  3.ª oleada del ingles (2026-11-02), lote «operaciones y clientes». Mismas
//  reglas que `textos/propuestas.ts`: claves en espanol, espanol LITERAL (la
//  copia exacta de lo que pintaba el componente), `EN_CLIENTES` como `Record`
//  (una clave que falte no compila), ni dinero ni moneda, y las frases con un
//  trozo con formato van ENTERAS, con huecos (`interpolarNodos`).
//
//  Pantallas: `/clientes` y su ficha (pipeline y campanas del cliente),
//  `/comisiones` y `/captacion`.
//
//  ESPEJOS: `clientes.pipeline.etapa.*` traduce `ETAPA_CLIENTE_LABEL`
//  (`lib/cliente-pipeline.ts`) y `clientes.captacion.tipo.*` traduce
//  `ETIQUETA_TIPO` (`lib/captacion.ts`); `clientes.captacion.falta.*` son las
//  frases de `faltantesParaRevision`. Esos modulos siguen siendo la verdad en
//  espanol, y `textos/clientes.test.ts` exige que el espanol de aqui sea
//  IDENTICO. Las etapas de captacion reusan `CLAVE_ETAPA` de Comercial
//  negociacion (las mismas `ETIQUETA_ETAPA`).
//
//  GLOSARIO de este archivo (ademas del comun): captacion → prospecting (el
//  menu ya dice «Prospecting») · prospecto → prospect · bitacora → log ·
//  comision → commission · comision aplicada → applied commission · negociacion
//  validada → negotiation validated · razon social → legal name · regimen
//  fiscal → tax regime · uso de CFDI → CFDI use · C.P. fiscal → tax postal code (como admin y campañas) ·
//  predio → property · tasa de cierre → close rate · embudo → funnel.
