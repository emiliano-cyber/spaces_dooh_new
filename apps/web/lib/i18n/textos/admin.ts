//  ni dinero ni moneda, frases con negritas ENTERAS y con huecos.
//
//  GLOSARIO propio (decisiones del traductor, el dueno puede cambiarlas):
//  Administracion → «Settings» (como el menu) · organizacion → organization ·
//  ticket → ticket · control de cambios → change control · actualizaciones →
//  updates · razon social → legal entity (el NOMBRE de una, «legal name») ·
//  codigos de recuperacion → recovery codes · novedades → what’s new ·
