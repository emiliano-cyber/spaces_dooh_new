//  lib/i18n/textos/campanas.ts — LOS TEXTOS DEL MODULO DE CAMPANAS.
// ----------------------------------------------------------------------------
//  Lote «campanas y finanzas» de la version en ingles (2026-11-02). Mismas
//  reglas que el piloto (`textos/propuestas.ts`), sin excepcion:
//
//    · CLAVES en espanol, `campanas.<elemento>[.matiz]`, minusculas y sin
//      acentos. La clave NO es la frase.
//    · El ESPANOL es copia LITERAL de lo que habia en el componente, con sus
//      tildes, sus comillas y sus espacios en los bordes. Las frases que en
//      JSX ocupaban varias lineas van como JSX las pintaba: unidas por UN
//      espacio. Y donde JSX NO ponia espacio (una linea que empieza justo
//      despues de un elemento), tampoco aqui: `validacion.bajar.texto` lleva
//      «{arte}(su API…» pegado porque asi salia en pantalla.
//    · `EN_CAMPANAS` es `Record<ClaveCampanas, string>`: una clave inglesa que
//      falte NO compila.
//    · Ni una cifra de dinero ni un simbolo de moneda (GUARDIA 2 de
//      `dinero.test.ts`). Los importes y el ejemplo «212,500.50» entran por
//      hueco.
//    · Las frases con un elemento dentro van ENTERAS, con huecos, y se
//      rellenan con `interpolarNodos()`.
//    · Plurales con `.uno` / `.otros`. El espanol de las dos es el de siempre
//      (si decia «pantalla(s)» sigue diciendolo); el ingles concuerda.
//
//  Las etiquetas de estado (`CAMPANA_LABEL`, `ETAPA_LABEL`, …) siguen siendo la
//  verdad en espanol en su modulo; aqui van sus claves, y
//  `textos/campanas.test.ts` exige que el espanol de cada una sea IDENTICO al
//  de su modulo (como el menu con `nav.ts` y las propuestas con `estatus.ts`).
// ============================================================================

