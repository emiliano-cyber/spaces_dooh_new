//
//  EL DISENO DEL DASHBOARD ESTA APROBADO POR EL DUENO («perfecto», 26/10): de
//  esta pagina solo se traducen los textos. Ni una clase ni un nodo cambian;
//  lo mide `pantallas-inicio.test.ts` con el HTML espanol volcado antes y
//  despues.
//
//  `inicio.alerta.*` son los avisos que arma `construirAlertas`
//  (`lib/data/derive.ts`), que gano `idioma` con 'es' por omision: el espanol
//  es el literal de alli. `inicio.tipo-alerta.*` espejan `TIPOS_ALERTA`
//  (`lib/alertas-visibles.ts`), `inicio.tramo.*` a `TRAMOS_COBRANZA` y
//  `inicio.licencia.*` a `LICENCIA_LABEL`; `textos/inicio.test.ts` ata los
//  tres al literal del modulo.
//
//  Plurales con `.uno/.otros`: el espanol de las dos es el que ya se pintaba
//  aunque diga «vence en 1 días» o «hace 1 día(s)».
//
//  GLOSARIO de este archivo: ingreso → revenue · devengar → earn · margen →
//  margin · pipeline → pipeline · tasa de cierre → close rate · ganado → won ·
//  ocupacion → occupancy · espacio·dia → space·day · cara (de una fija) → face
//  · hueco → gap · por cobrar por antiguedad → receivables by age · cuota →
