// ----------------------------------------------------------------------------
//  Lote «comercial» de la version en ingles (2026-11-02). Cubre:
//
//    · `/comercial` (`app/(app)/(shell)/comercial/page.tsx`) y sus piezas de
//      `components/demo/comercial/`: la ficha del sitio (`SiteFicha`, con sus
//      cuadros de editar, tarifas por unidad, pausa, reubicar y eliminar), el
//      alta de pantalla, la reserva y la vision de Space Eye;
//    · Comercial negociacion (`components/demo/comercial-opex/ComercialOpex.tsx`).
//
//  Los codigos de negociacion van aparte, en `textos/codigos.ts`.
//
//  Las reglas son las de `diccionario.ts` y las del piloto
//  (`textos/propuestas.ts`), sin excepcion:
//
//    · CLAVES en espanol, `comercial.<pieza>.<elemento>[.matiz]`, minusculas y
//      sin acentos. La clave NO es la frase.
//    · El ESPANOL es una copia LITERAL de lo que habia escrito en el
//      componente: mismas tildes, mismas comillas «», mismos espacios en los
//      bordes. Una frase que empieza con espacio lo lleva porque en la pantalla
//      iba pegada a otro nodo.
//    · `EN_COMERCIAL` es `Record<ClaveComercial, string>`: una clave inglesa
//      que falte NO compila.
//    · Ni una cifra de dinero ni un simbolo de moneda (GUARDIA 2 de
//      `dinero.test.ts`): el «$» del rotulo de la tarifa y el «15,000.50» del
//      ejemplo entran por hueco.
//    · Las frases con un trozo en negrita o con un elemento dentro van ENTERAS,
//      con huecos `{nombre}`, y se rellenan con `interpolarNodos()`.
//    · Plurales con `.uno` / `.otros`. El espanol de las dos es el de siempre
//      (si el componente decia «meses» tambien con 1, las dos dicen «meses»).
//
//  ESPEJOS DE ETIQUETAS COMPARTIDAS. `SITIO_LABEL`, `CONTRATO_LABEL` y
//  `PAGO_LABEL` (`components/demo/StatusBadge.tsx`), `TIPO_MEDIO_LABEL`
//  (`lib/tipo-medio.ts`), `ETIQUETA_ETAPA` (`lib/captacion.ts`) y las etiquetas
//  de `lib/negociacion.ts` siguen siendo la verdad en espanol y NO se tocaron.
//  Aqui hay una clave por valor, con el MISMO espanol, y las pantallas del lote
//  pintan la clave. `pantallas-comercial.test.ts` exige que el espanol de cada
//  espejo reproduzca EXACTAMENTE la etiqueta original (igual que el menu con
//  `nav.ts` y los estatus de propuestas con `estatus.ts`).
//
//  GLOSARIO del lote (ampliado en `vault/03-Frontend/idiomas-es-en.md` §11):
//  el del piloto, mas reserva → booking (reservar → book; reservado → Booked),
//  ficha → profile (ficha tecnica → spec sheet), Comercial negociacion → Lease
//  negotiation (como el menu), catorcenal → every two weeks,
//  arrendador → landlord, predio → property, prospeccion → prospecting,
//  Comercial (el modulo) → Sales, como el menu.
