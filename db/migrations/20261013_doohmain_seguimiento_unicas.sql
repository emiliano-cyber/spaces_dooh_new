-- @tipo: esquema
-- ============================================================================
--  SEGUIMIENTO DE DOOHmain · las tres tablas aceptan lo que escribe el SDK.
-- ----------------------------------------------------------------------------
--  Encontrado el 13/10 publicando una campaña de punta a punta contra un
--  DOOHmain simulado (vault/07-Agentes/diario/2026-10-13.md). En toda base
--  levantada desde el repositorio, PUBLICAR EN DOOHmain FALLABA SIEMPRE:
--
--    · `20260805_objetos_solo_en_prod.sql` crea `doohmain_remote_campaigns`,
--      `doohmain_remote_lists` y `media_uploads` con `id bigint primary key`
--      SIN identidad y SIN las restricciones únicas.
--    · `20260901_doohmain_tracking.sql` las define bien, pero con
--      `create table if not exists`: como ya existían, no hace nada.
--    · El SDK (`doohmain_sdk/db.py`) registra con `ON CONFLICT (version)` y
--      `ON CONFLICT (screen_name, list_name, media_id)`, y Postgres responde
--      «there is no unique or exclusion constraint matching the ON CONFLICT
--      specification». Y sin identidad, el `insert` sin `id` fallaría igual.
--
--  Lo caro es CUÁNDO falla: después de `create_campaign`. Cada intento dejaba
--  una campaña vacía en DOOHmain, sin arte ni spot, y la aplicación lo daba
--  por publicado.
--
--  ─── Qué hace ─────────────────────────────────────────────────────────────
--  Lleva las tres tablas a la forma de `20260901`, sin recrearlas:
--    1. `id` pasa a identidad si no lo es ya, y la secuencia arranca DESPUÉS del
--       mayor `id` que haya: una base con filas no puede chocar con las suyas.
--    2. Las tres únicas (`uniq_version`, `uniq_screen_list_media`,
--       `uniq_media_version`) se agregan si no hay ya una única o llave sobre
--       esas mismas columnas — la base de la que salió `20260805` pudo
--       tenerlas con otro nombre.
--    3. Permisos de secuencia para el rol de la aplicación, que es con el que
--       conecta el SDK.
--
--  ─── Con registros repetidos, ABORTA ───────────────────────────────────────
--  No se borra ninguno para poder crear la única: cada fila es la prueba de
--  algo publicado en DOOHmain, y elegir cuál sobra es una decisión, no una
--  migración. Se nombra lo repetido y no se aplica nada. En la práctica no
--  debería pasar: sin las únicas, el SDK no podía escribir ninguna fila.
--
--  Aditiva e idempotente. Prueba: `apps/web/lib/test/doohmain-seguimiento.e2e.test.ts`.
-- ============================================================================
begin;

do $$
declare
  t           record;
  repetidos   text;
  ya_hay      boolean;
  roles_app   text[] := array['spaces_app', 'spaces_user'];
  r           text;
begin
  for t in
    select * from (values
      ('doohmain_remote_campaigns', 'uniq_version',           array['version']),
      ('doohmain_remote_lists',     'uniq_screen_list_media', array['screen_name', 'list_name', 'media_id']),
      ('media_uploads',             'uniq_media_version',     array['version'])
    ) as x(tabla, restriccion, columnas)
  loop
    -- 1 · `id` con identidad, empezando después del mayor.
    if not exists (
      select 1 from information_schema.columns
       where table_schema = 'public' and table_name = t.tabla and column_name = 'id'
         and (is_identity = 'YES' or column_default is not null)
    ) then
      execute format('alter table %I alter column id add generated by default as identity', t.tabla);
      execute format(
        'select setval(pg_get_serial_sequence(%L, ''id''), coalesce(max(id), 0) + 1, false) from %I',
        t.tabla, t.tabla);
    end if;

    -- 2 · La única, salvo que ya haya una sobre exactamente esas columnas.
    select exists (
      select 1
        from pg_constraint c
       where c.conrelid = t.tabla::regclass
         and c.contype in ('u', 'p')
         and (select array_agg(a.attname::text order by a.attname)
                from pg_attribute a
               where a.attrelid = c.conrelid and a.attnum = any (c.conkey))
             = (select array_agg(x order by x) from unnest(t.columnas) x)
    ) into ya_hay;

    if not ya_hay then
      execute format(
        'select string_agg(k, ''; '') from (
           select concat_ws('' / '', %s) || '' ('' || count(*) || '' veces)'' as k
             from %I group by %s having count(*) > 1 limit 5) d',
        (select string_agg(format('%I::text', c), ', ') from unnest(t.columnas) c),
        t.tabla,
        (select string_agg(format('%I', c), ', ') from unnest(t.columnas) c))
        into repetidos;
      if repetidos is not null then
        raise exception 'No se puede crear % en %: hay registros repetidos (%). Decide cuál se queda y vuelve a correr la migración.',
          t.restriccion, t.tabla, repetidos;
      end if;
      execute format('alter table %I add constraint %I unique (%s)',
        t.tabla, t.restriccion,
        (select string_agg(format('%I', c), ', ') from unnest(t.columnas) c));
    end if;
  end loop;

  -- 3 · Las secuencias nuevas, para el rol con el que conecta el SDK.
  foreach r in array roles_app loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('grant usage, select on all sequences in schema public to %I', r);
    end if;
  end loop;
end $$;

commit;
